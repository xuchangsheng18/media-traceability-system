"""Unique, immutable error-code registrations for the independent business API."""

import re
from collections.abc import Iterable
from types import MappingProxyType


def validate_error_definitions(definitions: Iterable[tuple[str, int]]) -> dict[str, int]:
    result: dict[str, int] = {}
    for code, status in definitions:
        if (
            code in result
            or not re.fullmatch(r"[A-Z][A-Z0-9_]{0,95}", code)
            or type(status) is not int
            or not 400 <= status <= 599
        ):
            raise ValueError("ERROR_CODE_DEFINITION_INVALID")
        result[code] = status
    return result


