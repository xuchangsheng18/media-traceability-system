ERROR_STATUS = MappingProxyType(validate_error_definitions(ERROR_DEFINITIONS))


class BusinessError(Exception):
    def __init__(self, code: str, http_status: int) -> None:
        if ERROR_STATUS.get(code) != http_status:
            raise ValueError("ERROR_CODE_UNREGISTERED_OR_STATUS_MISMATCH")
        self.code = code
        self.http_status = http_status
        super().__init__(code)
